#!/usr/bin/env python3
"""
Read the static site and produce an import bundle for WordPress.

Output: wp-theme/import/manifest.json plus one body file per page.
The bundle is rsynced to the server and consumed by import.php via
`wp eval-file`, which has the full WordPress API for meta, thumbnails,
sticky posts, and menus.
"""
import json, re, html, pathlib

SITE = pathlib.Path(__file__).resolve().parent.parent / "site"
OUT  = pathlib.Path(__file__).resolve().parent / "import"
(OUT / "pages").mkdir(parents=True, exist_ok=True)

