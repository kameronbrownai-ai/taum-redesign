def rel_links(s: str) -> str:
    s = re.sub(r'href="([a-z0-9-]+)\.html(#[a-z0-9-]+)?"', r'href="/\1/\2"', s)
    s = s.replace('href="/index/"', 'href="/"')
    s = re.sub(r'src="(images/[^"]+)"', r'src="{{THEME}}/assets/\1"', s)
    s = s.replace('src="mural-photo.jpg"', 'src="{{THEME}}/assets/images/mural-photo.jpg"')
    return s

def apply_shortcodes(s: str) -> str:
    # Don't replace inside href/mailto/tel attributes; only in text.
    parts = re.split(r'(<[^>]+>)', s)
    for i, p in enumerate(parts):
        if p.startswith("<"):
            continue
        for lit, sc in SHORTCODES:
            p = p.replace(lit, sc)
        parts[i] = p
    return "".join(parts)

def strip_editor_notes(s: str) -> str:
    return re.sub(r"<!--\s*── EDITOR'S NOTE.*?-->", "", s, flags=re.S)

manifest = {"pages": [], "events": [], "partners": [], "posts": [], "menu": []}

for slug, label in PAGES:
    src = (SITE / f"{slug}.html").read_text(encoding="utf-8")
    main = re.search(r"<main id=\"main\">(.*?)</main>", src, re.S).group(1)
    hero = re.search(r'<div class="(?:page-hero|faq-hero)([^"]*)">(.*?)</div>\s*</div>\s*</div>|<div class="(?:page-hero|faq-hero)([^"]*)">(.*?)</div>\s*</div>', main, re.S)
    # Robust hero extraction: find the first page-hero/faq-hero block by balancing divs.
    m = re.search(r'<div class="(page-hero|faq-hero)([^"]*)">', main)
    start = m.start()
    depth = 0; i = m.end(); hero_end = None
    depth = 1
    for tag in re.finditer(r"<div\b|</div>", main[m.end():]):
        depth += 1 if tag.group(0).startswith("<div") else -1
        if depth == 0:
            hero_end = m.end() + tag.end()
            break
    hero_html = main[start:hero_end]
    body_html = main[hero_end:]

    style  = (m.group(2) or "").strip()
    kicker = re.search(r'<p class="kicker">(.*?)</p>', hero_html, re.S)
    h1     = re.search(r"<h1>(.*?)</h1>", hero_html, re.S)
    lede   = re.search(r'<p class="lede"[^>]*>(.*?)</p>', hero_html, re.S) or re.search(r'<p style="max-width:38em[^"]*">(.*?)</p>', hero_html, re.S)
    photo  = re.search(r'<img src="([^"]+)"[^>]*alt="([^"]*)"', hero_html)
    actions= re.search(r'<div class="actions"[^>]*>(.*?)</div>', hero_html, re.S)

    title = html.unescape(re.sub(r"<[^>]+>", "", h1.group(1))).strip()
    # If the hero carried buttons, keep them at the top of the body so nothing is lost.
    if actions:
        body_html = f'<p class="hero-actions">{rel_links(actions.group(1)).strip()}</p>\n' + body_html

    body = strip_editor_notes(body_html)
    # The About page's partners section is generated by page-about.php from the Partners post type.
    if slug == "about":
        body = re.sub(r'<section id="partners">.*?</section>\s*', "", body, flags=re.S)
    # The gallery becomes a native gallery block; capture the images for the importer.
    gallery_items = []
    if slug == "gallery":
        for gm in re.finditer(r'<img src="([^"]+)" alt="([^"]*)"><span class="cap">(.*?)</span>', body):
            gallery_items.append({"src": gm.group(1), "alt": html.unescape(gm.group(2)), "caption": html.unescape(gm.group(3))})
        body = re.sub(r'<div class="gallery-grid">.*?</div>\s*(?=<div class="callout")', "{{GALLERY}}\n\n  ", body, flags=re.S)
    body = rel_links(body)
    body = apply_shortcodes(body)
    # Body pages have a <section><div class="wrap"> wrapper; page.php supplies that. Unwrap the FIRST one only.
    body = re.sub(r'^\s*<section>\s*<div class="wrap[^"]*">', "", body, count=1)
    body = re.sub(r'</div>\s*</section>\s*$', "", body.rstrip(), count=1)
    body = body.strip() + "\n"

    (OUT / "pages" / f"{slug}.html").write_text(body, encoding="utf-8")
    manifest["pages"].append({
        "slug": slug,
        "title": title,
        "kicker": html.unescape(re.sub(r"<[^>]+>", "", kicker.group(1))).strip() if kicker else "",
        "excerpt": apply_shortcodes(rel_links(lede.group(1))).strip() if lede else "",
        "hero_style": style,
        "photo": photo.group(1) if photo else "",
        "photo_alt": html.unescape(photo.group(2)) if photo else "",
        "menu_label": label,
        "gallery": gallery_items,
        "empty_body": slug == "news",  # page-news.php generates everything
    })
    if label:
        manifest["menu"].append({"label": label, "slug": slug})

